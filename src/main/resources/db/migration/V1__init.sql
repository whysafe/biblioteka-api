create table readers (
    id         bigint generated by default as identity primary key,
    full_name  varchar(200) not null,
    email      varchar(200) not null unique,
    phone      varchar(30),
    created_at timestamptz  not null default now()
);

create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(200) not null unique,
    password_hash varchar(100) not null,
    role          varchar(20)  not null check (role in ('LIBRARIAN', 'READER')),
    reader_id     bigint unique references readers (id),
    created_at    timestamptz  not null default now()
);

create table books (
    id               bigint generated by default as identity primary key,
    isbn             varchar(17)  not null unique,
    title            varchar(300) not null,
    author           varchar(200) not null,
    genre            varchar(100),
    published_year   integer,
    total_copies     integer      not null check (total_copies >= 0),
    available_copies integer      not null check (available_copies >= 0),
    created_at       timestamptz  not null default now(),
    check (available_copies <= total_copies)
);

create index idx_books_title on books (lower(title));
create index idx_books_author on books (lower(author));

create table loans (
    id          bigint generated by default as identity primary key,
    book_id     bigint         not null references books (id),
    reader_id   bigint         not null references readers (id),
    issued_on   date           not null,
    due_date    date           not null,
    returned_on date,
    renewals    integer        not null default 0,
    fine        numeric(10, 2) not null default 0,
    fine_paid   boolean        not null default false
);

create index idx_loans_reader_active on loans (reader_id) where returned_on is null;
create index idx_loans_due on loans (due_date) where returned_on is null;

create table reservations (
    id          bigint generated by default as identity primary key,
    book_id     bigint      not null references books (id),
    reader_id   bigint      not null references readers (id),
    status      varchar(20) not null check (status in ('WAITING', 'READY', 'FULFILLED', 'CANCELLED', 'EXPIRED')),
    created_at  timestamptz not null,
    ready_until date
);

create index idx_reservations_queue on reservations (book_id, status, created_at);
